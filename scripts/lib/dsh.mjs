import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, cpSync, chmodSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import yaml from 'js-yaml'

const run = (command, args, cwd) => {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' })
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed (${result.status ?? result.error?.message ?? 'unknown'})`)
}

export const runtimeBin = manifest => path.join(manifest.runtimeDir, 'node_modules/@deepseek-ai/dsh/lib/bin.js')
const runtimeInstalled = manifest => {
  try { return JSON.parse(readFileSync(path.join(manifest.runtimeDir, 'node_modules/@deepseek-ai/dsh/package.json'), 'utf8')).version === manifest.dshVersion }
  catch { return false }
}
export const dshEnv = (manifest, extra = {}) => ({ ...process.env, DSH_HOME: manifest.dshHome, ...extra })
export const dsh = (manifest, args, options = {}) =>
  spawnSync(process.execPath, [runtimeBin(manifest), ...args], { env: dshEnv(manifest), cwd: options.cwd ?? manifest.ohmysaHome, stdio: options.stdio ?? 'inherit' })

/** Install the exact pinned DSH runtime under ~/.ohmysa/runtime (npm, no npx: no npm_* env leaks into the Host). */
export function ensureRuntime(manifest) {
  if (runtimeInstalled(manifest)) return runtimeBin(manifest)
  console.log(`installing @deepseek-ai/dsh@${manifest.dshVersion} into ${manifest.runtimeDir}`)
  mkdirSync(manifest.runtimeDir, { recursive: true })
  writeFileSync(path.join(manifest.runtimeDir, 'package.json'), JSON.stringify({
    name: 'ohmysa-runtime', private: true, dependencies: { '@deepseek-ai/dsh': manifest.dshVersion },
  }, null, 2) + '\n')
  run('npm', ['install', '--no-audit', '--no-fund'], manifest.runtimeDir)
  if (!runtimeInstalled(manifest)) throw new Error(`DSH ${manifest.dshVersion} did not install into ${manifest.runtimeDir}`)
  return runtimeBin(manifest)
}

const pnpmInstall = (manifest, cwd, extra = []) => {
  let installed = spawnSync('pnpm', ['install', ...extra], { cwd, stdio: 'inherit' })
  if (installed.status !== 0) {
    // pnpm may pick a store on the project's filesystem (e.g. /tmp) that is not writable;
    // retry once with a store this deployment owns.
    const store = path.join(manifest.ohmysaHome, 'pnpm-store')
    console.log(`pnpm install failed in ${cwd}; retrying with --store-dir=${store}`)
    installed = spawnSync('pnpm', ['install', ...extra, `--store-dir=${store}`], { cwd, stdio: 'inherit' })
  }
  if (installed.status !== 0) throw new Error(`pnpm install failed in ${cwd}`)
}

/** Build a dependency from a pinned public source (repository + ref) and return a file: spec for the profile. */
const ensureSource = (manifest, name, spec) => {
  const ref = String(spec.ref ?? 'main')
  const dir = path.join(manifest.ohmysaHome, 'src', `${name}-${ref.slice(0, 12)}`)
  if (existsSync(path.join(dir, 'lib')) && existsSync(path.join(dir, 'package.json'))) {
    console.log(`source ${name}@${ref.slice(0, 12)} already built at ${dir}`)
    return `file:${dir}`
  }
  if (!existsSync(path.join(dir, '.git'))) {
    console.log(`cloning ${spec.repository} at ${ref.slice(0, 12)} -> ${dir}`)
    mkdirSync(path.dirname(dir), { recursive: true })
    run('git', ['clone', '--filter=blob:none', spec.repository, dir], manifest.ohmysaHome)
  }
  run('git', ['checkout', '--detach', ref], dir)
  console.log(`installing and building ${name}@${ref.slice(0, 12)} (pinned source)`)
  pnpmInstall(manifest, dir, ['--frozen-lockfile'])
  run('pnpm', ['build'], dir)
  if (!existsSync(path.join(dir, 'lib'))) throw new Error(`${name} built without producing lib/ in ${dir}`)
  return `file:${dir}`
}

const resolveDeps = (manifest) => {
  const deps = {}
  for (const [name, spec] of Object.entries(manifest.deps)) {
    deps[name] = spec && typeof spec === 'object' && spec.repository ? ensureSource(manifest, name, spec) : spec
  }
  return deps
}

const profilePackage = manifest => ({
  name: `dsh-profile-${manifest.profile}`, private: true,
  dependencies: resolveDeps(manifest),
  dsh: { profile: { bundles: manifest.bundles } },
})
const profilePatch = manifest => {
  const header = `# Generated by ohmysa from ohmysa.yaml — edit the manifest, then run \`ohmysa build\`.\n# A profile layer is applied after every bundle layer.\n`
  return header + yaml.dump(manifest.patch, { lineWidth: 120, noRefs: true })
}

/** Materialize the manifest into the DSH profile: create it from the web template when absent, then write its package.json, patch file and installed dependencies. */
const writeInstructions = manifest => {
  if (!manifest.instructions) return
  const source = path.isAbsolute(manifest.instructions) ? manifest.instructions : path.join(manifest.repo, manifest.instructions)
  if (!existsSync(source)) throw new Error(`instructions file not found: ${source}`)
  mkdirSync(manifest.dshHome, { recursive: true })
  const body = `<!-- GENERATED by ohmysa from ${manifest.instructions} — edit it there, then run \`ohmysa build\`. -->\n` + readFileSync(source, 'utf8')
  const target = path.join(manifest.dshHome, 'AGENTS.md')
  if (!existsSync(target) || readFileSync(target, 'utf8') !== body) { writeFileSync(target, body); console.log(`wrote ${target}`) }
}

/** Copy secret-bearing machine state (credentials, plugin settings) from another DSH home; contents are never printed. */
export function importState(manifest, from, { force = false } = {}) {
  const fromHome = from.startsWith('~') ? path.join(process.env.HOME, from.slice(1)) : path.resolve(from)
  if (path.resolve(fromHome) === path.resolve(manifest.dshHome)) throw new Error('import source and dshHome are the same directory')
  for (const item of manifest.import ?? []) {
    const source = path.join(fromHome, item), target = path.join(manifest.dshHome, item)
    if (!existsSync(source)) { console.log(`skip   ${item} (absent in ${fromHome})`); continue }
    if (existsSync(target) && !force) { console.log(`keep   ${item} (already present; --force to overwrite)`); continue }
    mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 })
    cpSync(source, target, { recursive: true, force: true, preserveTimestamps: true })
    if (item === '.credentials.yaml') chmodSync(target, 0o600)
    console.log(`copied ${item}`)
  }
}

export function buildProfile(manifest, { force = false } = {}) {
  ensureRuntime(manifest)
  writeInstructions(manifest)
  if (!existsSync(path.join(manifest.profileDir, 'cordis.yml'))) {
    if (!force) console.log(`creating profile ${manifest.profile} from the default web template`)
    mkdirSync(path.dirname(manifest.profileDir), { recursive: true })
    const created = dsh(manifest, [manifest.profile, '--from-default-profile', 'web', '--dump-config'], { stdio: 'ignore' })
    if (created.status !== 0) throw new Error(`could not create profile ${manifest.profile}`)
  }
  const write = (file, content) => {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : undefined
    if (current === content) return false
    writeFileSync(file, content)
    return true
  }
  const packageChanged = write(path.join(manifest.profileDir, 'package.json'), JSON.stringify(profilePackage(manifest), null, 2) + '\n')
  const patchChanged = write(path.join(manifest.profileDir, 'cordis.patch.yml'), profilePatch(manifest))
  if (manifest.npmrcFrom && !existsSync(path.join(manifest.profileDir, '.npmrc'))) {
    const from = manifest.npmrcFrom.startsWith('~') ? path.join(process.env.HOME, manifest.npmrcFrom.slice(1)) : manifest.npmrcFrom
    if (existsSync(from)) copyFileSync(from, path.join(manifest.profileDir, '.npmrc'))
  }
  if (packageChanged || patchChanged) {
    console.log('profile files updated; installing profile dependencies with pnpm')
    pnpmInstall(manifest, manifest.profileDir)
  } else {
    console.log('profile already matches the manifest; nothing to install')
  }
  return { profileDir: manifest.profileDir, packageChanged, patchChanged }
}
